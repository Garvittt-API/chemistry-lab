import type { ExperimentRecord } from "@virtual-chemistry-lab/experiment-schema";

import {
  REPORT_SECTION_IDS,
  type CalculationRecord,
  type ExperimentalDataTable,
  type NotebookProvenance,
  type NotebookSession,
  type ObservationRecord,
  type ReportChartPoint,
  type ReportChartSeries,
  type ReportCompletenessIssue,
  type ReportConfig,
  type ReportSectionId,
  type SimulationRunRecord,
} from "./schemas.js";

export const PROVENANCE_LABELS: Readonly<Record<NotebookProvenance, string>> = {
  user_entered: "User-entered observation",
  engine_calculated: "Calculated by scientific engine",
  simulation_generated: "Generated by virtual simulation (not a physical measurement)",
  reference_expected: "Reference / literature expectation",
  imported_external: "Imported external dataset",
};

export interface PracticalReport {
  readonly generatedAt: string;
  readonly config: ReportConfig;
  readonly includedSections: ReadonlyArray<ReportSectionId>;
  readonly completenessIssues: ReadonlyArray<ReportCompletenessIssue>;
  readonly isComplete: boolean;
  readonly titleSection: {
    readonly experimentTitle: string;
    readonly sessionTitle: string;
  };
  readonly identificationSection: {
    readonly experimentId: string;
    readonly experimentSlug: string;
    readonly experimentVersion: string;
    readonly experimentSchemaVersion: string;
    readonly disciplineId: string;
    readonly difficulty: string;
    readonly scientificReviewStatus: string;
    readonly integrityLabel: string;
  };
  readonly sessionInfoSection: {
    readonly sessionId: string;
    readonly status: string;
    readonly revision: number;
    readonly createdAt: string;
    readonly updatedAt: string;
    readonly completedAt?: string;
    readonly preLabChecklist: NotebookSession["preLabChecklist"];
    readonly hypothesisOrPlan: string;
  };
  readonly objectiveSection: {
    readonly shortDescription: string;
    readonly learningObjectives: ReadonlyArray<string>;
  };
  readonly theorySection: {
    readonly overview: string;
    readonly keyConcepts: ReadonlyArray<string>;
  };
  readonly equationsSection: ReadonlyArray<{
    readonly id: string;
    readonly expression: string;
    readonly description: string;
    readonly conditions: ReadonlyArray<string>;
    readonly assumptions: ReadonlyArray<string>;
    readonly variables: ReadonlyArray<{ symbol: string; meaning: string; unit?: string }>;
  }>;
  readonly apparatusSection: ReadonlyArray<{
    readonly name: string;
    readonly specification: string;
    readonly quantity: string;
    readonly purpose: string;
  }>;
  readonly chemicalsSection: ReadonlyArray<{
    readonly name: string;
    readonly formulaOrDescription: string;
    readonly amount: string;
    readonly hazards: string;
  }>;
  readonly safetySection: {
    readonly riskClassification: string;
    readonly riskRationale: string;
    readonly hazards: ReadonlyArray<string>;
    readonly protectiveEquipment: ReadonlyArray<string>;
    readonly disposal: ReadonlyArray<string>;
    readonly supervision: string;
  };
  readonly procedureSection: {
    readonly overview: string;
    readonly steps: ReadonlyArray<{ stepNumber: number; title: string; instructions: string }>;
  };
  readonly observationsSection: {
    readonly records: ReadonlyArray<ObservationRecord>;
    readonly emptyNotice?: string;
  };
  readonly dataTablesSection: {
    readonly tables: ReadonlyArray<ExperimentalDataTable>;
    readonly populatedTableCount: number;
  };
  readonly calculationsSection: {
    readonly sessionCalculations: ReadonlyArray<CalculationRecord>;
    readonly referenceFormulas: ReadonlyArray<{
      readonly title: string;
      readonly purpose: string;
      readonly unitsAndDimensions: string;
      readonly assumptions: ReadonlyArray<string>;
    }>;
  };
  readonly resultsSection: {
    readonly summaryItems: ReadonlyArray<{
      readonly label: string;
      readonly valueWithUnit: string;
      readonly provenance: NotebookProvenance;
      readonly modelNote?: string;
    }>;
    readonly emptyNotice?: string;
  };
  readonly graphsSection: {
    readonly charts: ReadonlyArray<ReportChartSeries>;
    readonly emptyNotice?: string;
  };
  readonly discussionSection: {
    readonly text: string | null;
    readonly missingNotice?: string;
  };
  readonly conclusionSection: {
    readonly text: string | null;
    readonly missingNotice?: string;
  };
  readonly sourcesOfErrorSection: {
    readonly experimentErrorSources: ReadonlyArray<string>;
    readonly modelLimitations: ReadonlyArray<string>;
    readonly studentErrorAnalysis: string | null;
  };
  readonly referencesSection: ReadonlyArray<string>;
  readonly disclosureSection: {
    readonly statement: string;
    readonly provenanceCounts: Readonly<Record<NotebookProvenance, number>>;
    readonly simulationRuns: ReadonlyArray<SimulationRunRecord>;
    readonly scientificReviewNotice: string;
  };
}

export function getDefaultReportConfigForExperiment(experiment: ExperimentRecord): ReportConfig {
  const excluded = new Set<ReportSectionId>();
  if (experiment.educational.theory.equations.length === 0) {
    excluded.add("equations");
  }
  if (experiment.calculations.mode === "not_applicable") {
    excluded.add("calculations");
  }
  return {
    includedSections: REPORT_SECTION_IDS.filter((id) => !excluded.has(id)),
    includeCharts: true,
  };
}

export function extractChartSeriesFromTables(
  tables: ReadonlyArray<ExperimentalDataTable>,
): ReadonlyArray<ReportChartSeries> {
  const charts: ReportChartSeries[] = [];

  for (const table of tables) {
    const numericCols = table.columns.filter((c) => c.kind === "numeric");
    if (numericCols.length < 2 || table.rows.length < 2) continue;

    const xCol =
      (table.xAxisColumnId ? numericCols.find((c) => c.id === table.xAxisColumnId) : undefined) ??
      numericCols[0]!;
    const yCol =
      (table.yAxisColumnId
        ? numericCols.find((c) => c.id === table.yAxisColumnId && c.id !== xCol.id)
        : undefined) ?? numericCols.find((c) => c.id !== xCol.id);

    if (!yCol) continue;

    const points: ReportChartPoint[] = [];
    const provSet = new Set<string>();
    for (const row of table.rows) {
      const xCell = row.cells[xCol.id];
      const yCell = row.cells[yCol.id];
      if (
        xCell &&
        yCell &&
        xCell.numericValue !== null &&
        yCell.numericValue !== null &&
        Number.isFinite(xCell.numericValue) &&
        Number.isFinite(yCell.numericValue)
      ) {
        points.push({
          x: xCell.numericValue,
          y: yCell.numericValue,
          provenance: row.provenance,
        });
        provSet.add(PROVENANCE_LABELS[row.provenance]);
      }
    }

    if (points.length >= 2) {
      const sortedPoints = [...points].sort((a, b) => a.x - b.x);
      charts.push({
        id: `chart-${table.id}`,
        tableId: table.id,
        title: `${table.title}: ${yCol.label} vs ${xCol.label}`,
        xLabel: xCol.label,
        xUnit: xCol.unit ?? "dimensionless",
        yLabel: yCol.label,
        yUnit: yCol.unit ?? "dimensionless",
        points: sortedPoints,
        provenanceSummary: `Plotted from ${sortedPoints.length} recorded row(s) (${[...provSet].join("; ")}).`,
      });
    }
  }

  return charts;
}

/**
 * Construct a scientifically honest, provenance-preserving practical report from
 * an actual saved `NotebookSession` and its versioned `ExperimentRecord`.
 *
 * Never fabricates missing observations, numerical values or conclusions.
 */
export function buildPracticalReport(
  session: NotebookSession,
  experiment: ExperimentRecord,
  customConfig?: Partial<ReportConfig>,
  generatedAt = new Date().toISOString(),
): PracticalReport {
  const defaultCfg = getDefaultReportConfigForExperiment(experiment);
  const rawSections = customConfig?.includedSections ?? defaultCfg.includedSections;
  const includeCharts = customConfig?.includeCharts ?? defaultCfg.includeCharts;

  // Enforce mandatory simulation & measurement disclosure section
  const sectionSet = new Set<ReportSectionId>(rawSections);
  sectionSet.add("title");
  sectionSet.add("simulation_disclosure");
  const includedSections = REPORT_SECTION_IDS.filter((s) => sectionSet.has(s));

  const issues: ReportCompletenessIssue[] = [];

  const checklistValues = Object.values(session.preLabChecklist);
  if (checklistValues.some((v) => !v)) {
    issues.push({
      sectionId: "session_info",
      severity: "incomplete_optional",
      message: "Pre-laboratory readiness checklist has unconfirmed items.",
    });
  }

  if (session.observations.length === 0) {
    issues.push({
      sectionId: "observations",
      severity: "missing_required",
      message: "No observations have been recorded in this session.",
    });
  }

  const populatedTables = session.dataTables.filter((t) => t.rows.length > 0);
  if (session.dataTables.length > 0 && populatedTables.length === 0) {
    issues.push({
      sectionId: "data_tables",
      severity: "incomplete_optional",
      message: "Experimental data table templates contain 0 recorded rows.",
    });
  }

  if (
    experiment.calculations.mode === "provided" &&
    session.calculations.length === 0 &&
    session.simulationRuns.length === 0
  ) {
    issues.push({
      sectionId: "calculations",
      severity: "missing_required",
      message:
        "This experiment specifies quantitative calculations, but no engine calculations or model runs are saved in the session.",
    });
  }

  const discussionText = session.userNotes.discussion.trim();
  if (discussionText.length === 0) {
    issues.push({
      sectionId: "discussion",
      severity: "missing_required",
      message: "Student discussion has not been entered.",
    });
  }

  const conclusionText = session.userNotes.conclusion.trim();
  if (conclusionText.length === 0) {
    issues.push({
      sectionId: "conclusion",
      severity: "missing_required",
      message:
        "Student conclusion has not been entered (the report generator never fabricates conclusions).",
    });
  }

  const provenanceCounts: Record<NotebookProvenance, number> = {
    user_entered: 0,
    engine_calculated: 0,
    simulation_generated: 0,
    reference_expected: 0,
    imported_external: 0,
  };

  for (const obs of session.observations) {
    provenanceCounts[obs.provenance] += 1;
  }
  for (const tbl of session.dataTables) {
    for (const row of tbl.rows) {
      provenanceCounts[row.provenance] += 1;
    }
  }
  provenanceCounts.engine_calculated += session.calculations.length;
  for (const run of session.simulationRuns) {
    for (const out of run.outputs) {
      provenanceCounts[out.provenance] += 1;
    }
  }

  const resultItems: Array<{
    label: string;
    valueWithUnit: string;
    provenance: NotebookProvenance;
    modelNote?: string;
  }> = [];

  for (const calc of session.calculations) {
    resultItems.push({
      label: `${calc.title} — ${calc.result.label}`,
      valueWithUnit: `${calc.result.formattedValue} ${calc.result.unit}`,
      provenance: "engine_calculated",
      modelNote: `${calc.provenance.modelId} v${calc.provenance.modelVersion} (engine v${calc.provenance.engineVersion})`,
    });
  }

  for (const run of session.simulationRuns) {
    for (const out of run.outputs) {
      resultItems.push({
        label: `Virtual lab output — ${out.label}`,
        valueWithUnit: `${out.formattedValue} ${out.unit}`,
        provenance: out.provenance,
        modelNote: `${run.modelId} v${run.modelVersion}`,
      });
    }
  }

  for (const obs of session.observations) {
    if (obs.value !== null && obs.unit) {
      const valStr =
        obs.precisionDecimals !== undefined
          ? obs.value.toFixed(obs.precisionDecimals)
          : String(obs.value);
      resultItems.push({
        label: obs.title,
        valueWithUnit: `${valStr} ${obs.unit}`,
        provenance: obs.provenance,
        modelNote: obs.modelId ? `${obs.modelId} (${obs.engineVersion ?? ""})` : undefined,
      });
    }
  }

  const charts = includeCharts ? extractChartSeriesFromTables(session.dataTables) : [];

  const modelLimitationsSet = new Set<string>();
  if ("model" in experiment.simulation && experiment.simulation.model) {
    for (const lim of experiment.simulation.model.limitations) {
      modelLimitationsSet.add(lim);
    }
  }
  for (const run of session.simulationRuns) {
    for (const lim of run.limitations) modelLimitationsSet.add(lim);
  }
  for (const calc of session.calculations) {
    for (const lim of calc.limitations) modelLimitationsSet.add(lim);
  }

  const allReferences = Array.from(
    new Set([...experiment.references.items.map((r) => r.citation), ...session.referenceCitations]),
  );

  return {
    generatedAt,
    config: { includedSections: [...includedSections], includeCharts },
    includedSections,
    completenessIssues: issues,
    isComplete: issues.every((i) => i.severity !== "missing_required"),
    titleSection: {
      experimentTitle: experiment.identity.title,
      sessionTitle: session.title,
    },
    identificationSection: {
      experimentId: experiment.identity.id,
      experimentSlug: experiment.identity.slug,
      experimentVersion: session.experimentVersion,
      experimentSchemaVersion: session.experimentSchemaVersion,
      disciplineId: experiment.classification.disciplineId,
      difficulty: experiment.classification.difficulty,
      scientificReviewStatus: experiment.review.scientificReviewStatus,
      integrityLabel: experiment.review.integrityLabel,
    },
    sessionInfoSection: {
      sessionId: session.sessionId,
      status: session.status,
      revision: session.revision,
      createdAt: session.createdAt,
      updatedAt: session.updatedAt,
      completedAt: session.completedAt,
      preLabChecklist: session.preLabChecklist,
      hypothesisOrPlan: session.userNotes.hypothesisOrPlan.trim(),
    },
    objectiveSection: {
      shortDescription: experiment.identity.shortDescription,
      learningObjectives: experiment.educational.learningObjectives,
    },
    theorySection: {
      overview: experiment.educational.theory.overview,
      keyConcepts: experiment.educational.theory.concepts,
    },
    equationsSection: experiment.educational.theory.equations.map((eq) => ({
      id: eq.id,
      expression: eq.displayForm ?? eq.expression,
      description: eq.description,
      conditions: eq.applicableConditions,
      assumptions: eq.assumptions,
      variables: eq.variables.map((v) => ({
        symbol: v.symbol,
        meaning: v.meaning,
        unit: v.unit,
      })),
    })),
    apparatusSection: experiment.materials.equipment.map((item) => ({
      name: item.name,
      specification: item.specification ?? "—",
      quantity: item.quantity !== undefined ? String(item.quantity) : "—",
      purpose: item.purpose ?? "—",
    })),
    chemicalsSection: experiment.materials.chemicals.map((chem) => ({
      name: chem.name,
      formulaOrDescription: chem.formulaOrDescription ?? "—",
      amount:
        typeof chem.amount === "object" && chem.amount !== null
          ? `${chem.amount.value} ${chem.amount.unit}`
          : (chem.amount ?? "—"),
      hazards: chem.hazardKinds.length > 0 ? chem.hazardKinds.join(", ") : "None listed",
    })),
    safetySection: {
      riskClassification: String(experiment.safety.riskClassification),
      riskRationale: experiment.safety.riskRationale,
      hazards: experiment.safety.hazards.map((h) => `${h.kind}: ${h.statement}`),
      protectiveEquipment: experiment.safety.protectiveEquipment,
      disposal: experiment.safety.disposal,
      supervision: experiment.safety.supervision.replace(/_/g, " "),
    },
    procedureSection: {
      overview: experiment.procedure.overview,
      steps: experiment.procedure.steps.map((st, idx) => ({
        stepNumber: idx + 1,
        title: st.title,
        instructions: st.instructions,
      })),
    },
    observationsSection: {
      records: session.observations,
      emptyNotice:
        session.observations.length === 0
          ? "MISSING INFORMATION: No qualitative or quantitative observations were recorded in this notebook session."
          : undefined,
    },
    dataTablesSection: {
      tables: session.dataTables,
      populatedTableCount: populatedTables.length,
    },
    calculationsSection: {
      sessionCalculations: session.calculations,
      referenceFormulas:
        experiment.calculations.mode === "provided"
          ? experiment.calculations.calculations.map((c) => ({
              title: c.title,
              purpose: c.purpose,
              unitsAndDimensions: c.unitsAndDimensions,
              assumptions: c.assumptions,
            }))
          : [],
    },
    resultsSection: {
      summaryItems: resultItems,
      emptyNotice:
        resultItems.length === 0
          ? "MISSING INFORMATION: No quantitative calculations, simulation outputs or numeric observations have been recorded yet."
          : undefined,
    },
    graphsSection: {
      charts,
      emptyNotice:
        charts.length === 0
          ? "No plottable numerical coordinate pairs (at least 2 rows with finite X and Y values) were recorded in the session data tables."
          : undefined,
    },
    discussionSection: {
      text: discussionText.length > 0 ? discussionText : null,
      missingNotice:
        discussionText.length === 0
          ? "INCOMPLETE: Student discussion was not entered prior to report generation."
          : undefined,
    },
    conclusionSection: {
      text: conclusionText.length > 0 ? conclusionText : null,
      missingNotice:
        conclusionText.length === 0
          ? "INCOMPLETE: Student conclusion was not entered. Automated conclusions are never fabricated."
          : undefined,
    },
    sourcesOfErrorSection: {
      experimentErrorSources:
        experiment.observations.mode === "provided"
          ? experiment.observations.content.errorSources
          : [],
      modelLimitations: [...modelLimitationsSet],
      studentErrorAnalysis:
        session.userNotes.errorAnalysis.trim().length > 0
          ? session.userNotes.errorAnalysis.trim()
          : null,
    },
    referencesSection: allReferences,
    disclosureSection: {
      statement:
        "IMPORTANT SCIENTIFIC DISCLOSURE: This report was generated from a digital Virtual Chemistry Lab notebook session. Values labelled 'Generated by virtual simulation' or 'Calculated by scientific engine' originate from deterministic mathematical models under idealised assumptions and are NOT physical laboratory instrument measurements. Nothing in this report claims that a physical wet-chemistry experiment was performed unless independently verified by an instructor.",
      provenanceCounts,
      simulationRuns: session.simulationRuns,
      scientificReviewNotice: `Experiment record review status: ${experiment.review.scientificReviewStatus} (${experiment.review.integrityLabel}). Simulation models in @virtual-chemistry-lab/simulation-core are reference-verified against automated test cases and remain pending independent human scientific review.`,
    },
  };
}
